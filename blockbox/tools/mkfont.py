# Rasterises DejaVu Sans Mono (Bitstream Vera licence) into a tiny 1-bit font header.
import sys
from PIL import Image, ImageDraw, ImageFont
font = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf', 9)
CW, CH = 6, 10
rows = []
for c in range(32, 127):
    im = Image.new('1', (CW, CH), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = '1'
    d.text((0, -1), chr(c), font=font, fill=1)
    glyph = []
    for y in range(CH):
        b = 0
        for x in range(CW):
            if im.getpixel((x, y)): b |= 1 << x
        glyph.append(b)
    rows.append(glyph)
out = ['/* Generated by tools/mkfont.py from DejaVu Sans Mono Bold (Bitstream Vera licence). */',
       '#define FONT_W %d' % CW, '#define FONT_H %d' % CH,
       'static const unsigned char FONT[95][%d] = {' % CH]
for c, g in zip(range(32, 127), rows):
    out.append('\t{%s}, /* %r */' % (','.join('0x%02x' % v for v in g), chr(c)))
out.append('};')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
# preview
prev = Image.new('L', (CW * 32 * 3, CH * 3 * 3), 0)
for i, g in enumerate(rows):
    for y in range(CH):
        for x in range(CW):
            if g[y] >> x & 1:
                for a in range(3):
                    for b in range(3):
                        prev.putpixel(((i % 32) * CW * 3 + x * 3 + a, (i // 32) * CH * 3 + y * 3 + b), 255)
prev.save(sys.argv[2])
